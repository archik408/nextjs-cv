/** Formats milliseconds as a zero-padded HH:MM:SS clock. */
export function formatElapsed(ms: number): string {
  const totalSeconds = Math.max(0, Math.floor(ms / 1000));
  const hours = Math.floor(totalSeconds / 3600);
  const minutes = Math.floor((totalSeconds % 3600) / 60);
  const seconds = totalSeconds % 60;
  return [hours, minutes, seconds].map((part) => String(part).padStart(2, '0')).join(':');
}

/** Clamps a custom timer value (minutes) to the supported 1–1440 range. */
export function clampCustomMinutes(value: number): number {
  if (!Number.isFinite(value)) {
    return MIN_CUSTOM_MINUTES;
  }
  const rounded = Math.round(value);
  return Math.min(MAX_CUSTOM_MINUTES, Math.max(MIN_CUSTOM_MINUTES, rounded));
}

/** Maps a duration preset id to minutes; `null` means "no limit". */
export function presetToMinutes(preset: DurationPreset, customMinutes: number): number | null {
  switch (preset) {
    case 'no-limit':
      return null;
    case '15m':
      return 15;
    case '30m':
      return 30;
    case '1h':
      return 60;
    case '2h':
      return 120;
    case 'custom':
      return clampCustomMinutes(customMinutes);
    default:
      return null;
  }
}
